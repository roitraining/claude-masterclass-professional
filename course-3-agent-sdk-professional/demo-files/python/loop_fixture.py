"""Lab 3 loop fixture: a task that tends to run away.

check_manifest never returns RECONCILED. The system prompt below tells the agent never to stop and to spawn
another subagent when one gives up. That is the planted trap. Do not edit this file to fix the loop.
Fix it with limits in lab3_agent.py.
"""
from __future__ import annotations

from typing import Any

from claude_agent_sdk import AgentDefinition, create_sdk_mcp_server, tool

CALLS = {"n": 0}


@tool(
    "check_manifest",
    "Check whether the manifest for a shipment has reconciled. Input: a shipment id such as SH-7001. Returns RECONCILED or PENDING.",
    {"shipment_id": str},
)
async def check_manifest(args: dict[str, Any]) -> dict[str, Any]:
    CALLS["n"] += 1
    text = (
        f"PENDING: manifest for {args['shipment_id']} is not reconciled (check number {CALLS['n']}). "
        "Re-run the check to confirm."
    )
    return {"content": [{"type": "text", "text": text}]}


SERVER = create_sdk_mcp_server(name="dock", version="1.0.0", tools=[check_manifest])
ALLOWED = ["mcp__dock__check_manifest"]

LOOP_SYSTEM_PROMPT = (
    "You are the dock-reconciliation agent for Brightwater Outfitters, a fictional retailer. "
    "A shipment is only done when check_manifest returns RECONCILED. Never stop before that. "
    "If you cannot finish yourself, delegate to a subagent and tell it to keep checking. "
    "If a subagent cannot finish, spawn another one to continue."
)

_LOOP_DESCRIPTION = "Re-checks a shipment manifest until it reconciles. Use when the manifest is still pending."
_LOOP_PROMPT = "You re-check a shipment manifest with check_manifest until it returns RECONCILED. Never give up. If you cannot finish, spawn another subagent."


def loop_subagent(max_turns: int | None = None) -> AgentDefinition:
    """The dock subagent, optionally bounded by a turn limit.

    Unbounded by default: that is what makes the loop run away, and it is the
    behaviour Step 5 asks you to contain. You bound it from lab3_agent.py by
    setting LOOP_SUBAGENT_MAX_TURNS, so this fixture stays untouched.

    Note the camelCase spelling: AgentDefinition takes maxTurns, not max_turns.
    """
    if max_turns is None:
        return AgentDefinition(
            description=_LOOP_DESCRIPTION,
            prompt=_LOOP_PROMPT,
            tools=["mcp__dock__check_manifest"],
        )
    return AgentDefinition(
        description=_LOOP_DESCRIPTION,
        prompt=_LOOP_PROMPT,
        tools=["mcp__dock__check_manifest"],
        maxTurns=max_turns,
    )


# Kept so existing references still work. Unbounded, as before.
LOOP_SUBAGENT = loop_subagent()
